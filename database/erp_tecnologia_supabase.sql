CREATE OR REPLACE FUNCTION fn_correlativo(p_prefijo TEXT) RETURNS TEXT
LANGUAGE plpgsql AS $$
DECLARE v BIGINT;
BEGIN
  v := CASE p_prefijo
         WHEN 'V'   THEN nextval('seq_venta')
         WHEN 'SR'  THEN nextval('seq_solicitud')
         WHEN 'ADQ' THEN nextval('seq_adquisicion')
         WHEN 'OC'  THEN nextval('seq_orden_compra')
         WHEN 'OS'  THEN nextval('seq_orden_servicio')
         WHEN 'RC'  THEN nextval('seq_recepcion')
       END;
  IF v IS NULL THEN RAISE EXCEPTION 'Prefijo de correlativo no válido: %', p_prefijo; END IF;
  RETURN p_prefijo || '-' || lpad(v::text, 6, '0');
END;
$$;

