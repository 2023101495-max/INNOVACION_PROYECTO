AFTER INSERT ON detalle_recepcion
FOR EACH ROW EXECUTE FUNCTION fn_detalle_recepcion_ai();

-- Único punto donde cambia el presupuesto
CREATE OR REPLACE FUNCTION fn_mov_presupuestal_bi() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
  v_asig   NUMERIC(14,2);
  v_comp   NUMERIC(14,2);
  v_estado VARCHAR(10);
BEGIN
  SELECT monto_asignado, monto_comprometido, estado
    INTO v_asig, v_comp, v_estado
    FROM presupuesto WHERE id_presupuesto = NEW.id_presupuesto
    FOR UPDATE;

  IF v_estado = 'CERRADO' THEN
    RAISE EXCEPTION 'El presupuesto del periodo está cerrado';
  END IF;

  NEW.disponible_anterior := v_asig - v_comp;

  CASE NEW.tipo
    WHEN 'ASIGNACION' THEN
      v_asig := v_asig + NEW.monto;
    WHEN 'REDUCCION' THEN
      IF NEW.monto > (v_asig - v_comp) THEN
        RAISE EXCEPTION 'La reducción supera el saldo disponible';
      END IF;
      v_asig := v_asig - NEW.monto;
    WHEN 'COMPROMISO' THEN
      IF NEW.monto > (v_asig - v_comp) THEN
        RAISE EXCEPTION 'No existe disponibilidad presupuestal suficiente';
      END IF;
      v_comp := v_comp + NEW.monto;
    WHEN 'LIBERACION' THEN
      IF NEW.monto > v_comp THEN
        RAISE EXCEPTION 'La liberación supera el monto comprometido';
      END IF;
      v_comp := v_comp - NEW.monto;
  END CASE;

  NEW.disponible_posterior := v_asig - v_comp;

  UPDATE presupuesto
     SET monto_asignado = v_asig, monto_comprometido = v_comp
   WHERE id_presupuesto = NEW.id_presupuesto;
  RETURN NEW;
END;
$$;

