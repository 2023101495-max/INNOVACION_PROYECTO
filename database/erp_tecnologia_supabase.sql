-- RF-INV-12: la recepción incrementa el stock y actualiza el estado de la orden
CREATE OR REPLACE FUNCTION fn_detalle_recepcion_ai() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
  v_producto  INT;
  v_orden     INT;
  v_usuario   INT;
  v_nro       VARCHAR(15);
  v_fecha     TIMESTAMP;
  v_pendiente INT;
BEGIN
  SELECT d.id_producto, d.id_orden INTO v_producto, v_orden
    FROM detalle_orden d WHERE d.id_detalle_orden = NEW.id_detalle_orden;

  SELECT id_usuario, nro_recepcion, fecha_recepcion INTO v_usuario, v_nro, v_fecha
    FROM recepcion WHERE id_recepcion = NEW.id_recepcion;

  INSERT INTO movimiento_inventario
    (id_producto, tipo, origen, cantidad, id_detalle_recepcion, fecha_hora, id_usuario, observacion)
  VALUES
    (v_producto, 'ENTRADA', 'RECEPCION', NEW.cantidad_recibida, NEW.id_detalle_recepcion,
     v_fecha, v_usuario, 'Ingreso por recepción ' || v_nro);

  -- unidades aún pendientes de recibir en la orden (solo líneas de producto)
  SELECT COALESCE(SUM(d.cantidad - COALESCE(r.recibido, 0)), 0) INTO v_pendiente
    FROM detalle_orden d
    LEFT JOIN (SELECT id_detalle_orden, SUM(cantidad_recibida) AS recibido
                 FROM detalle_recepcion GROUP BY id_detalle_orden) r
           ON r.id_detalle_orden = d.id_detalle_orden
   WHERE d.id_orden = v_orden AND d.id_producto IS NOT NULL;

  UPDATE orden
     SET estado = CASE WHEN v_pendiente = 0 THEN 'RECIBIDA' ELSE 'RECIBIDA_PARCIAL' END
   WHERE id_orden = v_orden;
  RETURN NULL;
END;
$$;

