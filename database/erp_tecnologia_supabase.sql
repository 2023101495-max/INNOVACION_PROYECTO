-- RF-ADM-06, 08, 09: aplicar la decisión de Finanzas
CREATE OR REPLACE FUNCTION fn_verificacion_au() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.decision IS NULL AND NEW.decision IS NOT NULL THEN
    IF NEW.decision = 'AUTORIZADA' THEN
      INSERT INTO movimiento_presupuestal
        (id_presupuesto, tipo, monto, id_verificacion, descripcion, fecha_hora, id_usuario)
      VALUES
        (NEW.id_presupuesto, 'COMPROMISO', NEW.monto_solicitado, NEW.id_verificacion,
         'Compromiso por verificación N° ' || NEW.id_verificacion,
         NEW.fecha_evaluacion, NEW.id_usuario_evalua);
    END IF;

    UPDATE adquisicion
       SET estado = CASE NEW.decision
                      WHEN 'AUTORIZADA' THEN 'AUTORIZADA'
                      WHEN 'RECHAZADA'  THEN 'RECHAZADA'
                      WHEN 'POSPUESTA'  THEN 'POSPUESTA'
                      WHEN 'REPLANTEAR' THEN 'SIN_DISPONIBILIDAD'
                    END
     WHERE id_adquisicion = NEW.id_adquisicion;

    INSERT INTO decision_adquisicion
      (id_adquisicion, unidad, decision, motivo, fecha_decision, id_usuario)
    VALUES
      (NEW.id_adquisicion, 'FINANZAS',
       CASE NEW.decision WHEN 'REPLANTEAR' THEN 'REPLANTEADA' ELSE NEW.decision END,
       COALESCE(NEW.observacion, 'Resultado de verificación presupuestal'),
       NEW.fecha_evaluacion, NEW.id_usuario_evalua);
  END IF;
  RETURN NULL;
END;
$$;

