-- RF-VEN-04, 05, 06: validar stock y calcular importe antes de vender
CREATE OR REPLACE FUNCTION fn_detalle_venta_bi() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
  v_stock  INT;
  v_precio NUMERIC(10,2);
  v_estado VARCHAR(10);
BEGIN
  SELECT stock_actual, precio_venta, estado
    INTO v_stock, v_precio, v_estado
    FROM producto WHERE id_producto = NEW.id_producto
    FOR UPDATE;

  IF v_estado <> 'ACTIVO' THEN
    RAISE EXCEPTION 'El producto no está activo para la venta';
  END IF;

  IF NEW.cantidad > v_stock THEN
    RAISE EXCEPTION 'Cantidad solicitada (%) supera el stock disponible (%)', NEW.cantidad, v_stock;
  END IF;

  IF NEW.precio_unitario IS NULL THEN
    NEW.precio_unitario := v_precio;
  END IF;

  NEW.importe := NEW.cantidad * NEW.precio_unitario;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_detalle_venta_bi
BEFORE INSERT ON detalle_venta
FOR EACH ROW EXECUTE FUNCTION fn_detalle_venta_bi();

-- RF-VEN-07, 10 / RF-INV-05: salida de inventario y total de la venta
CREATE OR REPLACE FUNCTION fn_detalle_venta_ai() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
  v_usuario INT;
  v_nro     VARCHAR(15);
  v_fecha   TIMESTAMP;
BEGIN
  SELECT id_usuario, nro_venta, fecha_hora INTO v_usuario, v_nro, v_fecha
    FROM venta WHERE id_venta = NEW.id_venta;

  INSERT INTO movimiento_inventario
    (id_producto, tipo, origen, cantidad, id_detalle_venta, fecha_hora, id_usuario, observacion)
  VALUES
    (NEW.id_producto, 'SALIDA', 'VENTA', NEW.cantidad, NEW.id_detalle_venta, v_fecha, v_usuario,
     'Salida por venta ' || v_nro);

  UPDATE venta SET total = total + NEW.importe WHERE id_venta = NEW.id_venta;
  RETURN NULL;
END;
$$;

CREATE TRIGGER trg_detalle_venta_ai
AFTER INSERT ON detalle_venta
FOR EACH ROW EXECUTE FUNCTION fn_detalle_venta_ai();

-- Único punto donde cambia el stock (RF-INV-05, 06, 07, 12, 14)
CREATE OR REPLACE FUNCTION fn_movimiento_inventario_bi() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
  v_stock INT;
BEGIN
  SELECT stock_actual INTO v_stock
    FROM producto WHERE id_producto = NEW.id_producto
    FOR UPDATE;

  IF NEW.tipo = 'SALIDA' AND NEW.cantidad > v_stock THEN
    RAISE EXCEPTION 'Stock insuficiente para registrar la salida (stock: %)', v_stock;
  END IF;

  NEW.stock_anterior  := v_stock;
  NEW.stock_posterior := CASE WHEN NEW.tipo = 'ENTRADA'
                              THEN v_stock + NEW.cantidad
                              ELSE v_stock - NEW.cantidad END;

  UPDATE producto SET stock_actual = NEW.stock_posterior
   WHERE id_producto = NEW.id_producto;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_movimiento_inventario_bi
BEFORE INSERT ON movimiento_inventario
FOR EACH ROW EXECUTE FUNCTION fn_movimiento_inventario_bi();

-- RF-INV-08, 09: generar / cerrar alertas de stock mínimo
CREATE OR REPLACE FUNCTION fn_producto_au() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.stock_actual < NEW.stock_minimo THEN
    IF NOT EXISTS (SELECT 1 FROM alerta_stock
                    WHERE id_producto = NEW.id_producto AND estado = 'PENDIENTE') THEN
      INSERT INTO alerta_stock (id_producto, stock_actual, stock_minimo)
      VALUES (NEW.id_producto, NEW.stock_actual, NEW.stock_minimo);
    ELSE
      UPDATE alerta_stock SET stock_actual = NEW.stock_actual
       WHERE id_producto = NEW.id_producto AND estado = 'PENDIENTE';
    END IF;
  ELSE
    UPDATE alerta_stock
       SET estado = 'ATENDIDA', fecha_atencion = (now() AT TIME ZONE 'America/Lima')
     WHERE id_producto = NEW.id_producto AND estado = 'PENDIENTE';
  END IF;
  RETURN NULL;
END;
$$;

CREATE TRIGGER trg_producto_au
AFTER UPDATE OF stock_actual, stock_minimo ON producto
FOR EACH ROW EXECUTE FUNCTION fn_producto_au();

-- RF-ADQ-06: total de la cotización
CREATE OR REPLACE FUNCTION fn_detalle_cotizacion_ai() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
  UPDATE cotizacion
     SET monto_total = monto_total + (NEW.cantidad * NEW.precio_unitario)
   WHERE id_cotizacion = NEW.id_cotizacion;
  RETURN NULL;
END;
$$;

CREATE TRIGGER trg_detalle_cotizacion_ai
AFTER INSERT ON detalle_cotizacion
