-- Supabase se usa solo como base de datos: la aplicación se conecta con el
-- usuario dueño de las tablas. Activar RLS sin políticas bloquea el acceso
-- por la API pública de Supabase (anon/authenticated) a todas las tablas.
DO $$
DECLARE r RECORD;
BEGIN
  FOR r IN SELECT tablename FROM pg_tables WHERE schemaname = current_schema() LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', r.tablename);
  END LOOP;
END $$;

-- Las vistas no usan RLS: se retira todo permiso a los roles de la API pública
-- (solo existen en Supabase; en otro PostgreSQL este bloque no hace nada).
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated';
    EXECUTE 'REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated';
    EXECUTE 'REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public FROM anon, authenticated';
  END IF;
END $$;

