-- RF-ADM-04, 05, 07: el sistema determina si hay disponibilidad al evaluar
CREATE OR REPLACE FUNCTION fn_verificacion_bu() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
  v_disp NUMERIC(14,2);
BEGIN
  IF OLD.resultado <> 'PENDIENTE' THEN
    RAISE EXCEPTION 'La verificación ya fue evaluada; registre una nueva';
  END IF;

  IF NEW.decision IS NOT NULL THEN
    SELECT monto_disponible INTO v_disp
      FROM presupuesto WHERE id_presupuesto = NEW.id_presupuesto;

    NEW.disponible_al_evaluar := v_disp;
    NEW.resultado := CASE WHEN v_disp >= NEW.monto_solicitado
                          THEN 'CON_DISPONIBILIDAD' ELSE 'SIN_DISPONIBILIDAD' END;
    NEW.fecha_evaluacion := COALESCE(NEW.fecha_evaluacion, now() AT TIME ZONE 'America/Lima');

    IF NEW.resultado = 'SIN_DISPONIBILIDAD' AND NEW.decision = 'AUTORIZADA' THEN
      RAISE EXCEPTION 'No se puede autorizar: no existe disponibilidad presupuestal';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

